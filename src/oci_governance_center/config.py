"""Operator settings; application credentials are encrypted in local storage."""

from pathlib import Path
from urllib.parse import urlsplit

from cryptography.fernet import Fernet
from pydantic import SecretStr, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="OGC_", extra="ignore", hide_input_in_errors=True)
    data_root: Path = Path(".ogc")
    public_base_url: str = "https://localhost:8443"
    encryption_key: SecretStr
    setup_password: SecretStr
    parent_package_url: str = ""
    child_package_url: str = ""
    max_workers: int = 4
    retention_days: int = 90
    session_seconds: int = 3600
    # Historical Audit hours read per scan; forward reads always catch up to the present.
    audit_backfill_hours: int = 168

    @field_validator("encryption_key")
    @classmethod
    def valid_encryption_key(cls, value: SecretStr) -> SecretStr:
        try:
            Fernet(value.get_secret_value().encode("ascii"))
        except ValueError:
            raise ValueError(
                "OGC_ENCRYPTION_KEY must be a Fernet key generated by `ogc encryption-key`. "
                "For existing data, restore the original key; do not generate a replacement."
            ) from None
        return value

    @field_validator("setup_password")
    @classmethod
    def strong_setup_password(cls, value: SecretStr) -> SecretStr:
        # The global unlock throttle cannot identify clients behind a proxy; length is the defense.
        if len(value.get_secret_value()) < 16:
            raise ValueError(
                "OGC_SETUP_PASSWORD must be at least 16 characters; use a long random value"
            )
        return value

    @field_validator("public_base_url")
    @classmethod
    def public_origin(cls, value: str) -> str:
        u = urlsplit(value)
        local_http = u.scheme == "http" and u.hostname in {"localhost", "127.0.0.1", "::1"}
        # Accessing port also rejects malformed and out-of-range port numbers.
        _ = u.port
        if (
            (u.scheme != "https" and not local_http)
            or not u.hostname
            or u.path not in ("", "/")
            or u.query
            or u.fragment
            or u.username
        ):
            raise ValueError(
                "OGC_PUBLIC_BASE_URL must be an HTTPS origin, or an HTTP origin on "
                "localhost, 127.0.0.1, or [::1] for local development. "
                "Use scheme, hostname, and port only, without a path such as /setup; "
                "for example http://127.0.0.1:8000"
            )
        return value.rstrip("/")

    @field_validator("max_workers", "retention_days", "session_seconds", "audit_backfill_hours")
    @classmethod
    def positive(cls, value: int) -> int:
        if value < 1:
            raise ValueError("Setting must be positive")
        return value
